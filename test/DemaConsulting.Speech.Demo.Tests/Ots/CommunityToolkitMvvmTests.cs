using NSubstitute;

namespace DemaConsulting.Speech.Demo.Tests.Ots;

/// <summary>
///     Integration tests for the CommunityToolkit.Mvvm OTS software item.
/// </summary>
/// <remarks>
///     The demo depends on this package's source generators for its change notification and
///     command plumbing, so these tests verify that the generated members genuinely exist and
///     behave, rather than assuming a source generator ran.
/// </remarks>
public partial class CommunityToolkitMvvmTests
{
    /// <summary>
    ///     Proves that the package's <c>ObservableProperty</c> generator produces a public property
    ///     that raises change notification, which is what keeps every bound demo panel current.
    /// </summary>
    [Fact]
    public void CommunityToolkitMvvm_ObservableProperty_Assigned_RaisesPropertyChanged()
    {
        // Arrange: a ViewModel whose plain (no dependent) observable state is generated by the package
        var row = new ModelListItemViewModel(FakeSpeechModel.Descriptor("model-a"));
        var changed = new List<string?>();
        row.PropertyChanged += (_, args) => changed.Add(args.PropertyName);

        // Act: assign through the generated property
        row.ProgressFraction = 0.5;

        // Assert: the generated setter stored the value and announced the change
        Assert.Equal(0.5, row.ProgressFraction);
        Assert.Contains(nameof(ModelListItemViewModel.ProgressFraction), changed);
    }

    /// <summary>
    ///     Proves that the package's <c>RelayCommand</c> generator produces a bindable command that
    ///     invokes the annotated method, which is what lets the demo's buttons stay code-behind
    ///     free.
    /// </summary>
    [Fact]
    public void CommunityToolkitMvvm_RelayCommand_Executed_InvokesAnnotatedMethod()
    {
        // Arrange: a ViewModel whose Refresh method is a genuinely synchronous (void) annotated
        // method, so the generator emits a plain relay command rather than an async one; the
        // catalog reports nothing at construction and one installed model afterwards
        var catalog = Substitute.For<IModelCatalogService>();
        catalog.Enumerate().Returns([]);
        var deviceService = Substitute.For<IAudioDeviceService>();
        deviceService.EnumerateCaptureDevices().Returns([]);
        deviceService.EnumeratePlaybackDevices().Returns([]);
        var viewModel = new RecognitionPanelViewModel(
            catalog,
            deviceService,
            new DeviceSelectionViewModel(deviceService),
            Substitute.For<IRecognizerSessionFactory>());
        Assert.Empty(viewModel.AvailableModels);
        catalog.Enumerate().Returns(
            [FakeSpeechModel.Descriptor("stt-a", SpeechModelState.Downloaded, role: SpeechModelRole.Recognition)]);

        // Act: execute the generated command the way a bound button does
        var command = viewModel.RefreshCommand;
        var canExecute = command.CanExecute(null);
        command.Execute(null);

        // Assert: the command is synchronous and the annotated method ran to completion
        Assert.False(command is IAsyncRelayCommand);
        Assert.True(canExecute);
        Assert.Equal("stt-a", Assert.Single(viewModel.AvailableModels).Id);
    }

    /// <summary>
    ///     Proves that a <c>RelayCommand</c> declared on an ordinary class that is not a demo view
    ///     model still gets a generated command, covering the generator prerequisites (a
    ///     <c>partial</c> class deriving from <c>ObservableObject</c>).
    /// </summary>
    [Fact]
    public void CommunityToolkitMvvm_RelayCommand_TestLocalPartialClass_GeneratesSynchronousCommand()
    {
        // Arrange: a test-local partial class annotated with a synchronous command
        var subject = new SynchronousCommandSubject();

        // Act: run the generated command
        subject.IncrementCommand.Execute(null);

        // Assert: the command exists, is synchronous, and ran the annotated method once
        Assert.False(subject.IncrementCommand is IAsyncRelayCommand);
        Assert.Equal(1, subject.Count);
    }

    /// <summary>
    ///     Proves that the package's <c>RelayCommand</c> generator produces a cancellable async
    ///     command for an asynchronous method, which is what lets the demo run a model download
    ///     without blocking the UI thread.
    /// </summary>
    [Fact]
    public async Task CommunityToolkitMvvm_AsyncRelayCommand_Executed_AwaitsAnnotatedMethod()
    {
        // Arrange: a ViewModel with a generated asynchronous command over one downloadable model
        var service = Substitute.For<IModelCatalogService>();
        service.Enumerate().Returns([FakeSpeechModel.Descriptor("model-a")]);
        service
            .DownloadAsync("model-a", Arg.Any<IProgress<SpeechModelDownloadProgress>?>(), Arg.Any<CancellationToken>())
            .Returns(Task.FromResult(new SpeechModelDownloadResult(SpeechModelDownloadOutcome.Installed)));
        var viewModel = new ModelCatalogViewModel(service);

        // Act: execute the generated async command and await its completion
        var command = Assert.IsType<IAsyncRelayCommand>(viewModel.DownloadCommand, exactMatch: false);
        await command.ExecuteAsync(viewModel.Models[0]);

        // Assert: the awaited method completed and updated the row
        Assert.Equal(SpeechModelState.Downloaded, viewModel.Models[0].State);
    }

    /// <summary>
    ///     Proves that the asynchronous command generated for a method taking a
    ///     <see cref="CancellationToken"/> is cancellable: canceling the command signals the token
    ///     the annotated method received, which is what lets a user abort a model download.
    /// </summary>
    /// <returns>A task that completes when the test has finished.</returns>
    [Fact]
    public async Task CommunityToolkitMvvm_AsyncRelayCommand_Canceled_SignalsTokenToAnnotatedMethod()
    {
        // Arrange: a download that stays in flight until its token is canceled
        var started = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        var service = Substitute.For<IModelCatalogService>();
        service.Enumerate().Returns([FakeSpeechModel.Descriptor("model-a")]);
        service
            .DownloadAsync("model-a", Arg.Any<IProgress<SpeechModelDownloadProgress>?>(), Arg.Any<CancellationToken>())
            .Returns(async callInfo =>
            {
                started.SetResult();
                await Task.Delay(Timeout.Infinite, callInfo.Arg<CancellationToken>());
                return new SpeechModelDownloadResult(SpeechModelDownloadOutcome.Installed);
            });
        var viewModel = new ModelCatalogViewModel(service);
        var row = viewModel.Models[0];
        var command = Assert.IsAssignableFrom<IAsyncRelayCommand>(viewModel.DownloadCommand);

        // Act: start the command, wait until the method is running, then cancel it
        var execution = command.ExecuteAsync(row);
        await started.Task.WaitAsync(TestContext.Current.CancellationToken);
        Assert.True(command.CanBeCanceled);
        command.Cancel();
        await execution;

        // Assert: the annotated method observed the cancellation and the row is offered again
        Assert.True(command.IsCancellationRequested);
        Assert.Equal(SpeechModelState.NotDownloaded, row.State);
        Assert.Equal("Download canceled.", row.FailureMessage);
    }

    /// <summary>
    ///     Proves that <c>NotifyPropertyChangedFor</c> makes the generated setter also announce the
    ///     dependent computed property, which is what keeps derived bound text current.
    /// </summary>
    [Fact]
    public void CommunityToolkitMvvm_NotifyPropertyChangedFor_StateAssigned_RaisesDependentPropertyChanged()
    {
        // Arrange: a row whose State setter is annotated to notify the derived StatusText
        var row = new ModelListItemViewModel(FakeSpeechModel.Descriptor("model-a"));
        var changed = new List<string?>();
        row.PropertyChanged += (_, args) => changed.Add(args.PropertyName);

        // Act: assign the source property
        row.State = SpeechModelState.Downloaded;

        // Assert: the dependent computed properties were announced as well
        Assert.Contains(nameof(ModelListItemViewModel.StatusText), changed);
        Assert.Contains(nameof(ModelListItemViewModel.CanDownload), changed);
    }

    /// <summary>
    ///     Test-local partial class proving the generator prerequisites for a synchronous command.
    /// </summary>
    private sealed partial class SynchronousCommandSubject : ObservableObject
    {
        /// <summary>
        ///     Gets the number of times the annotated method has run.
        /// </summary>
        public int Count { get; private set; }

        /// <summary>
        ///     Increments <see cref="Count"/>; the generator emits <c>IncrementCommand</c> for it.
        /// </summary>
        [RelayCommand]
        private void Increment() => Count++;
    }
}
