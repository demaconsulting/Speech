/// <summary>
///     System-level tests of the whole English phonemization package through its public API
///     (<see cref="EnglishPhonemizer"/> and the two renderers) with the real embedded data and, where stated, the real
///     <c>EnglishTextAnalyzer</c>: the golden corpora (about 150 own-written sentences, one reviewed sentence per
///     reading id), the priority order of the pronunciation sources, the reporting of unknown and unsupported text, the
///     restriction of the renderings to the symbols of the two voice models, the weak forms and determinism.
/// </summary>
/// <remarks>
///     The expected columns of the golden files are regenerated by the tools project's <c>regenerate-goldens</c>
///     command and then reviewed line by line; a changed line is a behavior change that must be reviewed, and a wrong
///     line is fixed in the code, never accepted into the golden. A word marked <c>!oov</c> is pronounced by the
///     trained letter-to-sound model (see <c>oov-golden.tsv</c> for its pinned behavior), so those lines change when the
///     model is retrained.
/// </remarks>
public sealed class SpeechPhonemesEnTests
{
    /// <summary>The share of reading sentences the real classifier must label correctly (measured 97.5%).</summary>
    private const double MinimumClassifierHitRate = 0.95;

    /// <summary>The symbols of the Piper voice.</summary>
    private static readonly SymbolInventory Piper = SymbolInventory.LoadPiper(TestFile("en_US-libritts_r-medium.onnx.trimmed.json"));

    /// <summary>The symbols of the Kokoro vocabulary.</summary>
    private static readonly SymbolInventory Kokoro = SymbolInventory.LoadKokoro(TestFile("kokoro-v1.0-tokenizer.json"));

    /// <summary>Proves every sentence of the golden corpus produces exactly its reviewed word stream.</summary>
    [Fact]
    public void SpeechPhonemesEn_SentenceGolden_EverySentenceProducesItsReviewedWordStream()
    {
        // Arrange
        var cases = GoldenCorpus.ReadSentences(TestFile("sentences-golden.tsv"));

        // Act
        var failures = cases
            .Select(c => (Case: c, Actual: GoldenCorpus.Format(GoldenCorpus.RunEndToEnd(c.Sentence))))
            .Where(t => t.Actual != t.Case.Expected)
            .Select(t => $"{t.Case.Id}: {t.Case.Sentence}\n  expected: {t.Case.Expected}\n  actual:   {t.Actual}")
            .ToList();

        // Assert: the corpus is the size the plan calls for, with unique ids and nothing left empty
        Assert.True(cases.Count >= 150);
        Assert.Equal(cases.Count, cases.Select(c => c.Id).Distinct(StringComparer.Ordinal).Count());
        Assert.All(cases, c => Assert.NotEmpty(c.Expected));
        Assert.Empty(failures);
    }

    /// <summary>Proves the readings golden: every reading id has one sentence and its reviewed pronunciation comes out of the pipeline (end to end, or with the reading forced where the classifier labels the sentence differently).</summary>
    [Fact]
    public void SpeechPhonemesEn_ReadingGolden_EveryReadingIsPronouncedAsReviewed()
    {
        // Arrange
        var cases = GoldenCorpus.ReadReadings(TestFile("readings-golden.tsv"));
        var failures = new List<string>();

        // Act
        foreach (var c in cases)
        {
            var forced = c.Mode == "forced";
            var result = forced ? GoldenCorpus.RunForced(c.Sentence, c.Target, c.ReadingId) : GoldenCorpus.RunEndToEnd(c.Sentence);
            var item = GoldenCorpus.FindWord(result, c.Target);
            if (item is null || !item.FromReading || item.ReadingId != c.ReadingId || item.Arpabet != c.Expected)
            {
                failures.Add($"{c.ReadingId} ({c.Mode}): expected '{c.Expected}' with reading applied, got '{item?.Arpabet}' reading '{item?.ReadingId}' applied {item?.FromReading}");
            }
        }

        // Assert: one case per reading id of the inventory, all as reviewed
        Assert.Equal(ReadingInventory.Default.ReadingIds.Order(StringComparer.Ordinal), cases.Select(c => c.ReadingId).Order(StringComparer.Ordinal));
        Assert.All(cases, c => Assert.Contains(c.Mode, new[] { "e2e", "forced" }));
        Assert.Empty(failures);
    }

    /// <summary>Proves the real classifier labels at least the gated share of the readings golden sentences correctly (its hit rate on own-written sentences).</summary>
    [Fact]
    public void SpeechPhonemesEn_ReadingGolden_ClassifierHitRate_MeetsTheGate()
    {
        // Arrange
        var cases = GoldenCorpus.ReadReadings(TestFile("readings-golden.tsv"));

        // Act: count the rows the committed mode says the classifier gets right, and re-check each against the classifier now
        var endToEnd = cases.Where(c => c.Mode == "e2e").ToList();
        var stale = endToEnd.Where(c => GoldenCorpus.ClassifiedReading(c.Sentence, c.Target) != c.ReadingId).Select(c => c.ReadingId).ToList();

        // Assert
        Assert.Empty(stale);
        Assert.True((double)endToEnd.Count / cases.Count >= MinimumClassifierHitRate, $"hit rate {endToEnd.Count}/{cases.Count}");
    }

    /// <summary>Proves that without an analysis every spelling of the inventory is pronounced as its default reading: the first variant of the dictionary, taken from the dictionary and from nothing else.</summary>
    [Fact]
    public void SpeechPhonemesEn_Phonemize_NoAnnotations_EveryInventoryFormGetsItsDefaultReading()
    {
        // Arrange
        var phonemizer = new EnglishPhonemizer();
        var forms = File.ReadLines(TestFile("forms.tsv")).Skip(1).Where(l => l.Length > 0).Select(l => l.Split('\t')[0])
            .Distinct(StringComparer.Ordinal).Where(f => CmuLexicon.Default.Contains(f)).ToList();

        // Act
        var wrong = forms.Where(f =>
        {
            var item = phonemizer.Phonemize(f).Items[0];
            return item.FromReading || item.Source != PronunciationSource.Lexicon || item.Arpabet != CmuLexicon.Default.Lookup(f)[0].ToString();
        }).ToList();

        // Assert: nearly all 501 forms are in the dictionary
        Assert.True(forms.Count >= 480);
        Assert.Empty(wrong);
    }

    /// <summary>Proves the dictionary is the source of a known word: the first variant is the default, case and the typographic apostrophe do not matter, and the word is reported as from the lexicon.</summary>
    [Fact]
    public void SpeechPhonemesEn_Phonemize_DictionaryWords_UseTheDictionaryPronunciation()
    {
        // Arrange
        var phonemizer = new EnglishPhonemizer();

        // Act
        var result = phonemizer.Phonemize("Cat RECORD don\u2019t");

        // Assert: the dictionary's own entries, in any case and with either apostrophe, and nothing reported as unknown
        Assert.Equal(["K AE1 T", "R AH0 K AO1 R D", "D OW1 N T"], result.Items.Select(i => i.Arpabet));
        Assert.All(result.Items, i => Assert.Equal(PronunciationSource.Lexicon, i.Source));
        Assert.Empty(result.OovWords);
    }

    /// <summary>Proves the priority order of the pronunciation sources on one text: a host override, then the reading the analysis chose, then the dictionary, then the morphology rules, then the letter-to-sound model, each visible in the item's source.</summary>
    [Fact]
    public void SpeechPhonemesEn_Phonemize_SourcesInPriorityOrder_OverrideReadingLexiconMorphologyLetterToSound()
    {
        // Arrange: "record" twice (an override and a reading), a dictionary word, a derived word and an unknown word
        var phonemizer = new EnglishPhonemizer();
        const string text = "record record cat unfollowed Zorblax";
        SegmentAnnotation[] annotations =
        [
            new(0, 6, TextEnAnnotations.Pronunciation, "arpabet:R IY0 K AO1 R D"),
            new(7, 6, TextEnAnnotations.Reading, "record.noun"),
        ];

        // Act
        var result = phonemizer.Phonemize(text, annotations);

        // Assert: the sources come out in priority order, and the enumeration order is the priority order
        Assert.Equal(
            [PronunciationSource.Override, PronunciationSource.Reading, PronunciationSource.Lexicon, PronunciationSource.Morphology, PronunciationSource.LetterToSound],
            result.Items.Select(i => i.Source));
        Assert.Equal(result.Items.Select(i => i.Source).Order(), result.Items.Select(i => i.Source));
        Assert.Equal("R IY0 K AO1 R D", result.Items[0].Arpabet);
        Assert.Equal("R EH1 K ER0 D", result.Items[1].Arpabet);
    }

    /// <summary>Proves forms the dictionary lacks are derived from a known stem by the documented sound rules (plural, past, productive prefix) instead of being guessed.</summary>
    [Fact]
    public void SpeechPhonemesEn_Phonemize_InflectedAndPrefixedWordsAbsentFromTheDictionary_AreDerivedFromTheirStem()
    {
        // Arrange: words that are not dictionary entries but a known stem plus an ending or a prefix
        var phonemizer = new EnglishPhonemizer();
        string[] words = ["unfollowed", "unfollows", "unfollow"];

        // Act
        var result = phonemizer.Phonemize(string.Join(' ', words));

        // Assert: none is reported out of vocabulary and each is derived by the morphology rules
        Assert.All(words, w => Assert.False(CmuLexicon.Default.Contains(w), w + " is a dictionary entry"));
        Assert.All(result.Items, i => Assert.Equal(PronunciationSource.Morphology, i.Source));
        Assert.Empty(result.OovWords);
        Assert.EndsWith("D", result.Items[0].Arpabet, StringComparison.Ordinal);
        Assert.EndsWith("Z", result.Items[1].Arpabet, StringComparison.Ordinal);
    }

    /// <summary>Proves a word that is in neither the dictionary nor derivable is pronounced by the trained model, flagged out of vocabulary and reported, and is never silent.</summary>
    [Fact]
    public void SpeechPhonemesEn_Phonemize_UnknownWord_IsPronouncedByTheModelAndReported()
    {
        // Act
        var result = new EnglishPhonemizer().Phonemize("Welcome Zorblax and Kathmandu");

        // Assert: the dictionary word is not reported; the two unknown words are pronounced, flagged and listed
        Assert.False(result.Items[0].Oov);
        Assert.Equal(["Zorblax", "Kathmandu"], result.OovWords);
        Assert.All(result.Items.Where(i => i.Oov), i =>
        {
            Assert.Equal(PronunciationSource.LetterToSound, i.Source);
            Assert.NotEmpty(i.Phones);
        });
    }

    /// <summary>Proves text that cannot be pronounced is kept as an unsupported item and listed, not dropped, and nothing else is lost: every word and mark of the text is an item.</summary>
    [Fact]
    public void SpeechPhonemesEn_Phonemize_UnsupportedText_IsKeptAndReportedNeverDropped()
    {
        // Act
        var result = new EnglishPhonemizer().Phonemize("Hi \U0001F600 there, \u65E5\u672C.");

        // Assert
        Assert.Equal(["Hi", "\U0001F600", "there", ",", "\u65E5\u672C", "."], result.Items.Select(i => i.Text));
        Assert.Equal(["\U0001F600", "\u65E5\u672C"], result.UnsupportedTokens);
    }

    /// <summary>Proves the text analysis drives the pronunciation: a normalized abbreviation and a currency amount are spoken as words, an initialism is spelled by letter names and a heteronym gets the reading the analysis chose.</summary>
    [Fact]
    public void SpeechPhonemesEn_Phonemize_AnalyzedText_SpeaksNormalizationsSpelledLettersAndReadings()
    {
        // Act
        var result = GoldenCorpus.RunEndToEnd("Dr. Smith paid $5 for the FBI record.");

        // Assert: the abbreviation and the amount are spoken as the words the analysis gave
        Assert.Contains(result.Items, i => i.Text == "Doctor" && i.Arpabet == "D AA1 K T ER0");
        Assert.Contains(result.Items, i => i.Text == "five" && i.Arpabet == "F AY1 V");

        // Assert: the initialism is spelled by its letter names
        Assert.Equal(["EH1 F", "B IY1", "AY1"], result.Items.Where(i => i.Source == PronunciationSource.Spelled).Select(i => i.Arpabet));

        // Assert: the noun reading of the heteronym is applied
        var record = Assert.Single(result.Items, i => i.Text == "record");
        Assert.True(record.FromReading);
        Assert.Equal("R EH1 K ER0 D", record.Arpabet);
    }

    /// <summary>Proves both renderers emit only symbols of their voice model for the whole sentence corpus, and that the rendering is non-empty for every sentence.</summary>
    [Fact]
    public void SpeechPhonemesEn_Render_SentenceCorpus_UsesOnlySymbolsOfTheVoiceModels()
    {
        // Arrange
        var sentences = GoldenCorpus.ReadSentences(TestFile("sentences-golden.tsv")).Select(c => c.Sentence).ToList();
        var piperRenderer = new EspeakIpaRenderer();
        var kokoroRenderer = new MisakiRenderer();

        // Act
        var missing = new List<string>();
        foreach (var sentence in sentences)
        {
            var phonemized = GoldenCorpus.RunEndToEnd(sentence);
            var ipa = piperRenderer.Render(phonemized);
            var misaki = kokoroRenderer.Render(phonemized);
            if (ipa.Length == 0 || misaki.Length == 0 || Piper.Missing(ipa).Any() || Kokoro.Missing(misaki).Any())
            {
                missing.Add(sentence);
            }
        }

        // Assert
        Assert.True(sentences.Count >= 150);
        Assert.Empty(missing);
    }

    /// <summary>Proves the voices' own conventions: the Piper rendering reduces function words (weak forms) by default and has them switchable, and the Kokoro rendering keeps the full forms unless asked.</summary>
    [Fact]
    public void SpeechPhonemesEn_Render_FunctionWords_AreWeakForPiperAndFullForKokoroByDefault()
    {
        // Arrange
        var phonemized = new EnglishPhonemizer().Phonemize("a cup of the tea");

        // Act
        var piperWeak = new EspeakIpaRenderer().Render(phonemized);
        var piperFull = new EspeakIpaRenderer(EspeakIpaProfile.EnUs, useWeakForms: false).Render(phonemized);
        var kokoroDefault = new MisakiRenderer().Render(phonemized);
        var kokoroWeak = new MisakiRenderer(MisakiProfile.Us, useWeakForms: true).Render(phonemized);

        // Assert: "of" is unstressed and joined to "the" in the weak Piper text, stressed otherwise, and weak only on request for Kokoro
        Assert.Equal("ɐ kˈʌp ʌvðə tˈiː", piperWeak);
        Assert.Contains("ˈʌv", piperFull, StringComparison.Ordinal);
        Assert.Contains("ˈʌv", kokoroDefault, StringComparison.Ordinal);
        Assert.DoesNotContain("ˈʌv", kokoroWeak, StringComparison.Ordinal);
    }

    /// <summary>Proves a long text is rendered as parts that each fit the limit of a voice model and end at a clause boundary without losing a sound, for both voices.</summary>
    [Fact]
    public void SpeechPhonemesEn_Render_LongText_IsSplitAtClauseBoundariesWithinTheLimit()
    {
        // Arrange: forty sentences, far more than one model input
        const int limit = 200;
        var phonemized = new EnglishPhonemizer().Phonemize(string.Join(' ', Enumerable.Repeat("The cat sat on the mat, and the dog barked loudly.", 40)));

        foreach (var (parts, whole) in new[]
        {
            (new EspeakIpaRenderer().RenderParts(phonemized, limit), new EspeakIpaRenderer().Render(phonemized)),
            (new MisakiRenderer().RenderParts(phonemized, limit), new MisakiRenderer().Render(phonemized)),
        })
        {
            // Assert: several parts, each within the limit and ending at a clause mark, together carrying every sound of the whole
            Assert.True(parts.Count >= 5);
            Assert.All(parts, part => Assert.InRange(part.EnumerateRunes().Count(), 1, limit));
            Assert.All(parts.Take(parts.Count - 1), part => Assert.Contains(part[^1], ",."));
            Assert.Equal(whole.Replace(" ", string.Empty, StringComparison.Ordinal), string.Concat(parts).Replace(" ", string.Empty, StringComparison.Ordinal));
        }
    }

    /// <summary>Proves the whole pipeline is deterministic: the same texts through fresh phonemizers on many threads at once give exactly the rendered strings of a single-threaded run.</summary>
    [Fact]
    public void SpeechPhonemesEn_Pipeline_RepeatedAndConcurrentRuns_GiveIdenticalResults()
    {
        // Arrange: forty sentences of the corpus, rendered once in sequence
        var sentences = GoldenCorpus.ReadSentences(TestFile("sentences-golden.tsv")).Select(c => c.Sentence).Take(40).ToList();
        var expected = sentences.Select(Render).ToList();

        // Act: four rounds of the same sentences, all at once
        var actual = new string[sentences.Count * 4];
        Parallel.For(0, actual.Length, i => actual[i] = Render(sentences[i % sentences.Count]));

        // Assert
        Assert.Equal(expected.Concat(expected).Concat(expected).Concat(expected), actual);
    }

    /// <summary>
    ///     Phonemizes a sentence with a fresh phonemizer and renders it for both voices.
    /// </summary>
    /// <param name="sentence">The sentence.</param>
    /// <returns>The word stream and the two phoneme strings, joined.</returns>
    private static string Render(string sentence)
    {
        var phonemized = new EnglishPhonemizer().Phonemize(sentence);
        return GoldenCorpus.Format(phonemized) + "|" + new EspeakIpaRenderer().Render(phonemized) + "|" + new MisakiRenderer().Render(phonemized);
    }

    /// <summary>
    ///     Gets the path of a test data file beside the test assembly.
    /// </summary>
    /// <param name="name">The file name.</param>
    /// <returns>The full path.</returns>
    private static string TestFile(string name) => Path.Combine(AppContext.BaseDirectory, "TestData", name);
}
