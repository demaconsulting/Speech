    /// <summary>Proves every sentence of the golden corpus produces exactly its reviewed word stream.</summary>
    [Fact]
    public void SpeechPhonemesEn_SentenceGolden_EverySentenceProducesItsReviewedWordStream()
    {
        // Arrange
        var cases = GoldenCorpus.ReadSentences(TestFile("sentences-golden.tsv"));

        // Act
        var failures = cases
            .Select(c => (Case: c, Actual: GoldenCorpus.Format(GoldenCorpus.RunEndToEnd(c.Sentence))))
            .Where(t => t.Actual != t.Case.Expected)
            .Select(t => $"{t.Case.Id}: {t.Case.Sentence}\n  expected: {t.Case.Expected}\n  actual:   {t.Actual}")
            .ToList();

        // Assert: the corpus is the size the plan calls for, with unique ids and nothing left empty
        Assert.True(cases.Count >= 150);
        Assert.Equal(cases.Count, cases.Select(c => c.Id).Distinct(StringComparer.Ordinal).Count());
        Assert.All(cases, c => Assert.NotEmpty(c.Expected));
        Assert.Empty(failures);
    }

    /// <summary>Proves the readings golden: every reading id has one sentence and its reviewed pronunciation comes out of the pipeline (end to end, or with the reading forced where the classifier labels the sentence differently).</summary>
    [Fact]
    public void SpeechPhonemesEn_ReadingGolden_EveryReadingIsPronouncedAsReviewed()
    {
        // Arrange
        var cases = GoldenCorpus.ReadReadings(TestFile("readings-golden.tsv"));
        var failures = new List<string>();

        // Act
        foreach (var c in cases)
        {
            var forced = c.Mode == "forced";
            var result = forced ? GoldenCorpus.RunForced(c.Sentence, c.Target, c.ReadingId) : GoldenCorpus.RunEndToEnd(c.Sentence);
            var item = GoldenCorpus.FindWord(result, c.Target);
            if (item is null || !item.FromReading || item.ReadingId != c.ReadingId || item.Arpabet != c.Expected)
            {
                failures.Add($"{c.ReadingId} ({c.Mode}): expected '{c.Expected}' with reading applied, got '{item?.Arpabet}' reading '{item?.ReadingId}' applied {item?.FromReading}");
            }
        }

        // Assert: one case per reading id of the inventory, all as reviewed
        Assert.Equal(ReadingInventory.Default.ReadingIds.Order(StringComparer.Ordinal), cases.Select(c => c.ReadingId).Order(StringComparer.Ordinal));
        Assert.All(cases, c => Assert.Contains(c.Mode, new[] { "e2e", "forced" }));
        Assert.Empty(failures);
    }

