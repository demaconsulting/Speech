using DemaConsulting.Speech.Phonemes.En.Tools.PhonemizerSubsystem;

namespace DemaConsulting.Speech.Phonemes.En.Tests;

/// <summary>
///     System-level golden test of the whole English phonemization pipeline: about 150 own-written sentences (numbers,
///     dates, times, currency, acronyms, contractions, possessives, hyphenation, heteronyms, unknown words,
///     punctuation and unsupported symbols) run through the real <c>EnglishTextAnalyzer</c> and the
///     <c>EnglishPhonemizer</c>, compared with the reviewed word streams in <c>sentences-golden.tsv</c>.
/// </summary>
/// <remarks>
///     The expected column is regenerated by the tools project's <c>regenerate-goldens</c> command and then reviewed
///     line by line; a changed line is a behavior change that must be reviewed, and a wrong line is fixed in the code,
///     never accepted into the golden. A word marked <c>!oov</c> is pronounced by the trained letter-to-sound model
///     (see <c>oov-golden.tsv</c> for its pinned behavior), so those lines change when the model is retrained.
/// </remarks>
public sealed class SpeechPhonemesEnTests
{
    /// <summary>Proves every sentence of the golden corpus produces exactly its reviewed word stream.</summary>
    [Fact]
    public void SpeechPhonemesEn_SentenceGolden_EverySentenceProducesItsReviewedWordStream()
    {
        // Arrange
        var cases = GoldenCorpus.ReadSentences(Path.Combine(AppContext.BaseDirectory, "TestData", "sentences-golden.tsv"));

        // Act
        var failures = cases
            .Select(c => (Case: c, Actual: GoldenCorpus.Format(GoldenCorpus.RunEndToEnd(c.Sentence))))
            .Where(t => t.Actual != t.Case.Expected)
            .Select(t => $"{t.Case.Id}: {t.Case.Sentence}\n  expected: {t.Case.Expected}\n  actual:   {t.Actual}")
            .ToList();

        // Assert: the corpus is the size the plan calls for, with unique ids and nothing left undrafted
        Assert.True(cases.Count >= 150);
        Assert.Equal(cases.Count, cases.Select(c => c.Id).Distinct(StringComparer.Ordinal).Count());
        Assert.All(cases, c => Assert.NotEmpty(c.Expected));
        Assert.Empty(failures);
    }
}
