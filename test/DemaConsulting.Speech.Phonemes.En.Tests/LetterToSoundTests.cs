using DemaConsulting.Speech.Phonemes.En.LetterToSoundSubsystem;
using DemaConsulting.Speech.Phonemes.En.LexiconSubsystem;

namespace DemaConsulting.Speech.Phonemes.En.Tests;

/// <summary>
///     Subsystem tests of the letter-to-sound conversion that pronounces words the dictionary does not know: a golden
///     corpus of about a hundred realistic out-of-vocabulary words pinned to the shipped model's output (to detect any
///     drift of the weights), the guarantee that every spelling gets a sensible non-empty pronunciation, and stability
///     under concurrent use.
/// </summary>
/// <remarks>
///     <para>
///     <c>oov-golden.tsv</c> holds names, brands, neologisms and compounds that the CMU Pronouncing Dictionary lacks. Its
///     expected column is regenerated by the tools project's <c>regenerate-goldens --oov</c> command and then
///     reviewed; it is a regression baseline of the trained model, not an oracle: a doubtful pronunciation is listed in
///     <c>docs/evaluation/phonemes-en/oov.md</c>, never hand-corrected in the golden. The accuracy of the model on
///     held-out dictionary words is the tools project's <c>benchmark-lts</c> result, recorded in that document.
///     </para>
/// </remarks>
public sealed class LetterToSoundTests
{
    /// <summary>Proves every word of the golden corpus is really out of the dictionary and gets exactly its pinned pronunciation.</summary>
    [Fact]
    public void LetterToSound_OovGolden_EveryWordGetsItsPinnedPronunciation()
    {
        // Arrange
        var cases = ReadGolden();
        var lexicon = CmuLexicon.Default;

        // Act
        var actual = cases.Select(c => (c.Word, Expected: c.Expected, Actual: Convert(c.Word))).ToList();

        // Assert: the corpus is the intended size, genuinely out of vocabulary, and unchanged
        Assert.True(cases.Count >= 100);
        Assert.Equal(cases.Count, cases.Select(c => c.Word).Distinct(StringComparer.Ordinal).Count());
        Assert.All(cases, c => Assert.Empty(lexicon.Lookup(c.Word)));
        Assert.Empty(actual.Where(a => a.Expected != a.Actual).Select(a => $"{a.Word}: expected {a.Expected}, actual {a.Actual}"));
    }

    /// <summary>Proves a pronunciation is never empty for a word with letters and has exactly one primary stress when it has a vowel.</summary>
    [Fact]
    public void LetterToSound_DictionaryWords_AreNeverSilentAndHaveOnePrimaryStress()
    {
        // Arrange: every 40th dictionary word that has a vowel letter, so the test needs no external data and covers short and long words
        var words = CmuLexicon.Default.Entries().Where((_, i) => i % 40 == 0).Select(e => e.Word).Where(w => w.IndexOfAny(['a', 'e', 'i', 'o', 'u', 'y']) >= 0).ToList();

        // Act
        var results = words.Select(w => (Word: w, Pronunciation: Convert(w))).ToList();

        // Assert
        Assert.True(words.Count > 3000);
        Assert.All(results, r => Assert.NotEmpty(r.Pronunciation));
        Assert.All(results, r => Assert.Equal(1, r.Pronunciation.Split(' ').Count(p => p.EndsWith('1') && p.Length == 3)));
    }

    /// <summary>Proves odd spellings are pronounced without an exception: very long words, repeated letters, apostrophes and other characters.</summary>
    [Theory]
    [InlineData("zzzzzzzzzzzzzzzz")]
    [InlineData("aeiouaeiouaeiou")]
    [InlineData("'tis")]
    [InlineData("rock'n'roll")]
    [InlineData("o'brien's")]
    [InlineData("'''x'''")]
    [InlineData("x")]
    [InlineData("qwrtp")]
    [InlineData("www")]
    [InlineData("Straße")]
    [InlineData("ABC123")]
    public void LetterToSound_OddSpellings_GetANonEmptyPronunciation(string word)
    {
        // Arrange
        var letterToSound = LetterToSound.Default;

        // Act
        var found = letterToSound.TryConvert(word, out var pronunciation);

        // Assert: something a voice can say as a word, so at least one vowel
        Assert.True(found);
        Assert.Contains(pronunciation.ToString().Split(' '), p => p.Length == 3);
    }

    /// <summary>Proves a very long word is pronounced without failure and in proportion to its length.</summary>
    [Fact]
    public void LetterToSound_VeryLongWord_IsPronouncedWithoutFailure()
    {
        // Arrange
        var word = string.Concat(Enumerable.Repeat("supercalifragilistic", 200));

        // Act
        var found = LetterToSound.Default.TryConvert(word, out var pronunciation);

        // Assert: a pronunciation at least as long as the number of syllable-like units, and one primary stress
        Assert.True(found);
        Assert.True(pronunciation.Count > 1000);
        Assert.Single(pronunciation.ToString().Split(' '), p => p.EndsWith('1'));
    }

    /// <summary>Proves text without any letter has no pronunciation, rather than an empty one reported as success.</summary>
    [Theory]
    [InlineData("")]
    [InlineData("'")]
    [InlineData("123")]
    [InlineData("-")]
    public void LetterToSound_NoLetters_HasNoPronunciation(string text)
    {
        // Act
        var found = LetterToSound.Default.TryConvert(text, out var pronunciation);

        // Assert
        Assert.False(found);
        Assert.Equal(0, pronunciation.Count);
    }

    /// <summary>Proves the answer depends on the word alone: many threads converting the same words get the single-threaded answers.</summary>
    [Fact]
    public void LetterToSound_ConcurrentUse_GivesTheSingleThreadedAnswers()
    {
        // Arrange
        var words = ReadGolden().Select(c => c.Word).ToList();
        var expected = words.ToDictionary(w => w, Convert, StringComparer.Ordinal);

        // Act
        var mismatches = new System.Collections.Concurrent.ConcurrentBag<string>();
        Parallel.For(0, 64, _ =>
        {
            foreach (var word in words)
            {
                if (Convert(word) != expected[word])
                {
                    mismatches.Add(word);
                }
            }
        });

        // Assert
        Assert.Empty(mismatches);
    }

    /// <summary>Proves the shipped model resource stays within its one-megabyte budget.</summary>
    [Fact]
    public void LetterToSound_ModelResource_IsWithinTheSizeBudget()
    {
        // Arrange
        using var stream = typeof(LtsModel).Assembly.GetManifestResourceStream(LtsModel.ResourceName);

        // Assert
        Assert.NotNull(stream);
        Assert.InRange(stream.Length, 1, 1024 * 1024);
    }

    /// <summary>
    ///     Converts a word and returns the ARPAbet text.
    /// </summary>
    /// <param name="word">The word.</param>
    /// <returns>The pronunciation text.</returns>
    private static string Convert(string word)
    {
        LetterToSound.Default.TryConvert(word, out var pronunciation);
        return pronunciation.ToString();
    }

    /// <summary>
    ///     Reads the golden corpus.
    /// </summary>
    /// <returns>The words and their pinned pronunciations.</returns>
    private static List<(string Word, string Expected)> ReadGolden() =>
        File.ReadLines(Path.Combine(AppContext.BaseDirectory, "TestData", "oov-golden.tsv"))
            .Where(l => l.Length > 0 && l[0] != '#')
            .Select(l => l.Split('\t'))
            .Select(c => (c[0], c[1]))
            .ToList();
}
