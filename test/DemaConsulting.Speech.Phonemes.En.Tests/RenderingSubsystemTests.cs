        foreach (var word in words)
        {
            LetterToSound.Default.TryConvert(word, out var pronunciation);
            piperMissing.UnionWith(Piper.Missing(EspeakIpaRenderer.RenderPronunciation(pronunciation)));
            kokoroMissing.UnionWith(Kokoro.Missing(MisakiRenderer.RenderPronunciation(pronunciation)));
        }

        // Assert
        Assert.True(words.Count > 15_000);
        Assert.Empty(piperMissing);
        Assert.Empty(kokoroMissing);
    }

    /// <summary>Proves text with every kind of punctuation, the weak-form words and unsupported symbols renders to symbols of the models in every renderer mode.</summary>
    [Fact]
    public void RenderingSubsystem_Coverage_WeakFormWordsAndPunctuation_UseOnlySymbolsOfBothModels()
    {
        // Arrange: every weak-form word before a consonant and before a vowel, then every punctuation mark the tokenizer knows
        var words = WeakForms.Words.ToList();
        var text = string.Join(' ', words.Select(w => w + " cat")) + " " + string.Join(' ', words.Select(w => w + " apple"))
            + " -- (a) [b] {c} \"d\" «e» 'f' ... !! ?! ; : , . … — – 😀";
        var result = Phonemizer.Phonemize(text);

        // Act
        var piperWeak = new EspeakIpaRenderer().Render(result);
        var piperFull = new EspeakIpaRenderer(EspeakIpaProfile.EnUs, useWeakForms: false).Render(result);
        var kokoroFull = new MisakiRenderer().Render(result);
        var kokoroWeak = new MisakiRenderer(MisakiProfile.Us, useWeakForms: true).Render(result);

        // Assert
        Assert.True(words.Count >= 60);
        Assert.Empty(Piper.Missing(piperWeak));
        Assert.Empty(Piper.Missing(piperFull));
        Assert.Empty(Kokoro.Missing(kokoroFull));
        Assert.Empty(Kokoro.Missing(kokoroWeak));
        Assert.All(WeakForms.AllForms, f => Assert.Empty(Piper.Missing(f)));
    }

    /// <summary>Proves the layout: words are separated by a space, clause punctuation attaches to the word before it, and the models' stress and sound conventions appear.</summary>
    [Fact]
    public void RenderingSubsystem_Layout_WordsAndClausePunctuation_FollowTheModelConventions()
    {
        // Arrange
        var result = Phonemizer.Phonemize("Hello, world!");

        // Act
        var piper = new EspeakIpaRenderer().Render(result);
        var kokoro = new MisakiRenderer().Render(result);

        // Assert: stress mark before the vowel, long vowels and r-colored ER for Piper; the single-letter diphthong O and ɜɹ for Kokoro
        Assert.Equal("həlˈoʊ, wˈɜːld!", piper);
        Assert.Equal("həlˈO, wˈɜɹld!", kokoro);
    }

    /// <summary>Proves the layout of quotation marks and dashes: Piper has no symbol for them and pauses, Kokoro keeps its own marks.</summary>
    [Fact]
    public void RenderingSubsystem_Layout_QuotesAndDashes_AreRenderedPerModel()
    {
        // Arrange
        var quoted = Phonemizer.Phonemize("\"Yes,\" she said.");
        var dashed = Phonemizer.Phonemize("Wait - what?");

        // Act and assert
        Assert.Equal("jˈɛs, ʃiː sˈɛd.", new EspeakIpaRenderer().Render(quoted));
        Assert.Equal("“jˈɛs,” ʃˈi sˈɛd.", new MisakiRenderer().Render(quoted));
        Assert.Equal("wˈeɪt, wˌʌt?", new EspeakIpaRenderer().Render(dashed));
        Assert.Equal("wˈAt — wˈʌt?", new MisakiRenderer().Render(dashed));
    }

    /// <summary>Proves the espeak-style details of the weak-form table: the flap of <i>it</i> and <i>at</i> before a vowel, <i>on the</i> and <i>for the</i> as one group, and the secondary stress of a few more words, none of which misaki's profile has.</summary>
    [Fact]
    public void WeakForms_TryGet_EspeakStyleDetails_AreForPiperOnly()
    {
        // Arrange
        var flap = Phonemizer.Phonemize("well it is at all");
        var groups = Phonemizer.Phonemize("look on the table for the road");
        var demoted = Phonemizer.Phonemize("made between");

        // Assert: Piper flaps the t of it and at before a vowel; Kokoro keeps the t
        Assert.Equal("wˈɛl ɪɾ ɪz æɾ ˈɔːl", new EspeakIpaRenderer().Render(flap));
        Assert.Equal("wˈɛl ɪt ɪz æt ˈɔl", new MisakiRenderer(MisakiProfile.Us, useWeakForms: true).Render(flap));

        // Assert: on the has no mark on on, for the is one group with the reduced vowel
        Assert.Equal("lˈʊk ɔnðə tˈeɪbəl fɚðə ɹˈoʊd", new EspeakIpaRenderer().Render(groups));

        // Assert: made and between have the secondary stress in the espeak-style text, the primary in misaki's
        Assert.Equal("mˌeɪd bᵻtwˌiːn", new EspeakIpaRenderer().Render(demoted));
        Assert.Equal("mˈAd bətwˈin", new MisakiRenderer(MisakiProfile.Us, useWeakForms: true).Render(demoted));
    }

    /// <summary>Proves both models stress the first part of a hyphenated compound and give the later parts a secondary stress, so the voice reads one compound word and not two stressed words with a break between them.</summary>
    [Fact]
    public void RenderingSubsystem_Compounds_StressTheFirstPartAndSecondTheLaterOnes()
    {
        // Arrange
        var result = Phonemizer.Phonemize("a well-known author");
        var battlefield = Phonemizer.Phonemize("a battle-field and twenty-one self-evident ones");

        // Assert
        Assert.Equal("ɐ wˈɛlnˌoʊn ˈɔθɚ", new EspeakIpaRenderer().Render(result));
        Assert.Equal("ə wˈɛlnˌOn ˈɔθəɹ", new MisakiRenderer().Render(result));

        // Assert: the secondary stress stands where the second element starts, next to the primary one or not
        Assert.Equal("ɐ bˈæɾəlfˌiːld ænd twˈɛntiwˌʌn sˈɛlfˌɛvədənt wˈʌnz", new EspeakIpaRenderer().Render(battlefield));
    }

    /// <summary>
    ///     Proves the vowels before r follow the espeak-ng en-us conventions the Piper voices were trained on: the
    ///     vowel of NEAR is a lax i (<i>here</i> is <c>hˈɪɹ</c>, never <c>hˈiːɹ</c>, which the voice hears as <i>he</i>),
    ///     the diphthongs before r end in a schwa (<c>aɪɚ</c>, <c>aʊɚ</c>) with the linking r before a vowel, the
    ///     vowel of CURE stays short for every spelling, and the other r-colored vowels (SQUARE, NORTH, FORCE, START,
    ///     NURSE, lettER) keep their symbols.
    /// </summary>
    [Fact]
    public void RenderingSubsystem_SoundRules_RColoredVowels_FollowTheEspeakConventions()
    {
        // Arrange: the word and the rendering of the espeak-ng en-us voice
        (string Word, string Expected)[] cases =
        [
            ("here", "hˈɪɹ"), ("ear", "ˈɪɹ"), ("dear", "dˈɪɹ"), ("fear", "fˈɪɹ"), ("year", "jˈɪɹ"), ("beer", "bˈɪɹ"),
            ("cheer", "tʃˈɪɹ"), ("clear", "klˈɪɹ"), ("appear", "ɐpˈɪɹ"), ("hearing", "hˈɪɹɪŋ"), ("tier", "tˈɪɹ"),
            ("inspire", "ɪnspˈaɪɚ"), ("admire", "ɐdmˈaɪɚ"), ("firing", "fˈaɪɚɹɪŋ"), ("fire", "fˈaɪɚ"), ("hour", "ˈaʊɚ"),
            ("poor", "pˈʊɹ"), ("poorer", "pˈʊɹɹɚ"), ("cure", "kjˈʊɹ"), ("square", "skwˈɛɹ"), ("share", "ʃˈɛɹ"),
            ("north", "nˈɔːɹθ"), ("force", "fˈɔːɹs"), ("start", "stˈɑːɹt"), ("nurse", "nˈɜːs"), ("letter", "lˈɛɾɚ"),
        ];

        // Act
        var rendered = cases.Select(c => (c.Word, Actual: new EspeakIpaRenderer().Render(Phonemizer.Phonemize(c.Word)), c.Expected)).ToList();

        // Assert
        Assert.All(rendered, r => Assert.Equal(r.Expected, r.Actual));
        Assert.Equal("ðə kˈɑːɹ ɪz hˈɪɹ", new EspeakIpaRenderer().Render(Phonemizer.Phonemize("the car is here")));
    }

