    /// <summary>Proves the sound rules: the flap, the linking r, the stress marks, the secondary stress next to the primary, and the models' own vowel symbols.</summary>
    [Fact]
    public void RenderingSubsystem_SoundRules_FlapLinkingRAndStress_FollowTheModelConventions()
    {
        // Arrange and act
        var city = Phonemizer.Phonemize("city");
        var water = Phonemizer.Phonemize("water");
        var linked = Phonemizer.Phonemize("number is");
        var nobody = Phonemizer.Phonemize("nobody");

        // Assert: flap between a stressed and an unstressed vowel
        Assert.Equal("sˈɪɾi", new EspeakIpaRenderer().Render(city));
        Assert.Equal("sˈɪɾi", new MisakiRenderer().Render(city));
        Assert.Equal("wˈɔːɾɚ", new EspeakIpaRenderer().Render(water));
        Assert.Equal("wˈɔɾəɹ", new MisakiRenderer().Render(water));

        // Assert: Piper links a final r-colored vowel to a vowel-initial word with an r
        Assert.Equal("nˈʌmbɚɹ ɪz", new EspeakIpaRenderer().Render(linked));
        Assert.Equal("nˈʌmbəɹ ˈɪz", new MisakiRenderer().Render(linked));

        // Assert: a secondary stress right after the primary stress is dropped for Piper and kept for Kokoro; a final -y never has one
        Assert.DoesNotContain('ˌ', new EspeakIpaRenderer().Render(nobody));
        Assert.Equal("nˈObˌɑdi", new MisakiRenderer().Render(nobody));
    }

    /// <summary>Proves the weak forms: function words lose their stress and reduce in the Piper profile, and can be switched off; Kokoro has the full forms unless asked.</summary>
    [Fact]
    public void RenderingSubsystem_WeakForms_FunctionWords_AreUnstressedOnlyWhenEnabled()
    {
        // Arrange
        var sentence = Phonemizer.Phonemize("a cup of the tea");

        // Act
        var piperWeak = new EspeakIpaRenderer().Render(sentence);
        var piperFull = new EspeakIpaRenderer(EspeakIpaProfile.EnUs, useWeakForms: false).Render(sentence);
        var kokoroFull = new MisakiRenderer().Render(sentence);
        var kokoroWeak = new MisakiRenderer(MisakiProfile.Us, useWeakForms: true).Render(sentence);

        // Assert: the unstressed article and the group "of the" in one unit; the full form keeps the stress of "of"
        Assert.Equal("ɐ kˈʌp ʌvðə tˈiː", piperWeak);
        Assert.Equal("ɐ kˈʌp ˈʌv ðə tˈiː", piperFull);
        Assert.Contains("ˈʌv", piperFull, StringComparison.Ordinal);
        Assert.Contains("ˈʌv", kokoroFull, StringComparison.Ordinal);
        Assert.DoesNotContain("ˈʌv", kokoroWeak, StringComparison.Ordinal);
        Assert.Contains("ʌv", kokoroWeak, StringComparison.Ordinal);
    }

    /// <summary>Proves a host IPA pronunciation passes through unchanged and an unsupported token produces no sound and no extra space.</summary>
    [Fact]
    public void EspeakIpaRenderer_Render_IpaOverrideAndUnsupportedToken_AreHandledPerItem()
    {
        // Arrange
        var overridden = Phonemizer.Phonemize("record", [new SegmentAnnotation(0, 6, TextEnAnnotations.Pronunciation, "ipa:ɹɪˈkɔɹd")]);
        var unsupported = Phonemizer.Phonemize("Hi 😀 there");

        // Act and assert: the override is the host's own symbols
        Assert.Equal("ɹɪˈkɔɹd", new EspeakIpaRenderer().Render(overridden));
        Assert.Equal("ɹɪˈkɔɹd", new MisakiRenderer().Render(overridden));

        // Assert: one string per item, an empty one for the unsupported token, and the words joined by a single space
        var pieces = new EspeakIpaRenderer().RenderItems(unsupported.Items);
        Assert.Equal(unsupported.Items.Count, pieces.Count);
        Assert.Contains(string.Empty, pieces);
        Assert.Equal("hˈaɪ ðɛɹ", new EspeakIpaRenderer().Render(unsupported));
        Assert.Equal("hˈI ðˈɛɹ", new MisakiRenderer().Render(unsupported));
    }

    /// <summary>Proves a long text is rendered as parts that stay within the symbol limit, end after a clause mark and lose no sound, for both renderers.</summary>
    [Fact]
    public void RenderingSubsystem_Parts_LongText_StayWithinTheLimitAtClauseBoundariesWithoutLoss()
    {
        // Arrange: 40 sentences of about 40 symbols each
        const int limit = 100;
        var text = Phonemizer.Phonemize(string.Join(' ', Enumerable.Repeat("The cat sat on the mat, and the dog barked.", 40)));
        var piper = new EspeakIpaRenderer();
        var kokoro = new MisakiRenderer(MisakiProfile.Us, useWeakForms: true);

        foreach (var (parts, whole) in new[] { (piper.RenderParts(text, limit), piper.Render(text)), (kokoro.RenderParts(text, limit), kokoro.Render(text)) })
        {
            // Assert: several parts, each within the limit and ending at a clause mark, and together all the sounds of the whole
            Assert.True(parts.Count >= 10);
            Assert.All(parts, part => Assert.InRange(part.EnumerateRunes().Count(), 1, limit));
            Assert.All(parts.Take(parts.Count - 1), part => Assert.Contains(part[^1], ",."));
            Assert.Equal(whole.Replace(" ", string.Empty, StringComparison.Ordinal), string.Concat(parts).Replace(" ", string.Empty, StringComparison.Ordinal));
        }

        // Assert: a short text is one part equal to the plain rendering, and a soundless text has no part
        var short1 = Phonemizer.Phonemize("Hello there.");
        Assert.Equal([piper.Render(short1)], piper.RenderParts(short1, limit));
        Assert.Empty(kokoro.RenderParts(Phonemizer.Phonemize("\U0001F600"), limit));
    }

