/// <summary>
///     Tests of the renderers that turn a phonemized text into the phoneme string of a voice model: the Piper
///     espeak-style IPA (<see cref="EspeakIpaRenderer"/>) and the Kokoro misaki symbols (<see cref="MisakiRenderer"/>).
///     Subsystem level (<c>RenderingSubsystem_*</c>): the vocabulary-coverage gates (no symbol outside the Piper
///     <c>phoneme_id_map</c> or the Kokoro vocabulary, for every dictionary pronunciation, every out-of-vocabulary
///     conversion and every phone in every neighborhood) and the layout and sound rules of both renderers together.
///     Unit level: the two renderers (the golden corpora, the renderings of the 150 reviewed sentences with the model
///     token ids, and the argument checks), the WeakForms table and the shared PhonemeStream layout and splitter.
/// </summary>
/// <remarks>
///     <para>
///     The golden files <c>piper-ipa-golden.tsv</c> and <c>kokoro-misaki-golden.tsv</c> are regenerated by the tools
///     project's <c>regenerate-goldens --renderers</c> command and then reviewed; they are regression baselines, not
///     oracles. The agreement with the reference engines (espeak-ng, misaki) is measured locally by the tools project's
///     <c>measure-oracle</c> command and recorded as aggregate numbers in <c>docs/evaluation/phonemes-en/renderers.md</c>;
///     no engine output is committed.
///     </para>
///     <para>
///     The Piper inventory is a trimmed copy of the voice's <c>phoneme_id_map</c> (CC BY 4.0, attributed in the file);
///     the Kokoro inventory is the package's own <c>tokenizer.json</c>, linked into the test output.
///     </para>
/// </remarks>
public sealed class RenderingSubsystemTests
{
