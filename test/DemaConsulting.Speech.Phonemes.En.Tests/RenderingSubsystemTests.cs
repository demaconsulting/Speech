    /// <summary>
    ///     Removes the spaces and the secondary stress marks of a phoneme string, so a long text and its parts can be compared
    ///     (the first weak word of a part, the start of a new utterance, carries a mark the whole text does not have).
    /// </summary>
    /// <param name="phonemes">The phoneme string.</param>
    /// <returns>The string without spaces and secondary stress marks.</returns>
    private static string WithoutSpacesAndSecondaryStress(string phonemes) =>
        phonemes.Replace(" ", string.Empty, StringComparison.Ordinal).Replace("ˌ", string.Empty, StringComparison.Ordinal);

    /// <summary>
    ///     Asserts that a renderer golden corpus holds exactly what the pipeline and the renderer produce for its sentences.
    /// </summary>
    /// <param name="file">The golden file name.</param>
    /// <param name="render">The renderer of a phonemized text.</param>
    /// <param name="inventory">The symbol inventory of the model, for the token ids.</param>
    private static void AssertGolden(string file, Func<PhonemizedText, string> render, SymbolInventory inventory)
    {
        // Arrange
        var cases = GoldenCorpus.ReadRendered(TestFile(file));

        // Act
        var failures = cases
            .Select(c => (Case: c, Actual: render(GoldenCorpus.RunEndToEnd(c.Sentence))))
            .Where(t => t.Actual != t.Case.Phonemes || inventory.ToIds(t.Actual) != t.Case.Ids)
            .Select(t => $"{t.Case.Id}: {t.Case.Sentence}\n  expected: {t.Case.Phonemes}\n  actual:   {t.Actual}")
            .ToList();

        // Assert: the corpus is the sentences corpus, every phoneme string is non-empty, and nothing differs
        Assert.True(cases.Count >= 150);
        Assert.All(cases, c => Assert.NotEmpty(c.Phonemes));
        Assert.All(cases, c => Assert.Empty(inventory.Missing(c.Phonemes)));
        Assert.Empty(failures);
    }
