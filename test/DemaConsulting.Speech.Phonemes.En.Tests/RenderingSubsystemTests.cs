    /// <summary>Proves the inventories are the real ones: the Piper voice's 159 symbols and Kokoro's vocabulary.</summary>
    [Fact]
    public void RenderingSubsystem_Inventories_AreTheModelsOwnSymbolTables()
    {
        // Assert: the Piper map has the 159 symbols of the voice (the pad, bos and eos included); Kokoro's vocabulary has its 115 symbols
        Assert.Equal(159, Piper.Count);
        Assert.True(Piper.Contains('ɹ') && Piper.Contains('ˈ') && Piper.Contains('ᵻ') && Piper.Contains(' '));
        Assert.Equal(115, Kokoro.Count);
        Assert.True(Kokoro.Contains('ʧ') && Kokoro.Contains('A') && Kokoro.Contains('ᵊ') && Kokoro.Contains(' '));

        // Assert: the symbol strings the IPA translation validates against are those inventories
        Assert.Equal(Piper.Symbols.Order(), IpaSymbols.PiperSymbols.Order());
        Assert.Equal(Kokoro.Symbols.Order(), IpaSymbols.KokoroVocabulary.Order());
    }

    /// <summary>Proves every pronunciation of the dictionary (all variants of all words) renders to symbols of the Piper voice and of Kokoro.</summary>
    [Fact]
    public void RenderingSubsystem_Coverage_EveryDictionaryPronunciation_UsesOnlySymbolsOfBothModels()
    {
        // Arrange
        var piperMissing = new HashSet<char>();
        var kokoroMissing = new HashSet<char>();
        var count = 0;

        // Act
        foreach (var pronunciation in CmuLexicon.Default.Entries().SelectMany(e => e.Pronunciations))
        {
            var ipa = EspeakIpaRenderer.RenderPronunciation(pronunciation);
            var misaki = MisakiRenderer.RenderPronunciation(pronunciation);
            piperMissing.UnionWith(Piper.Missing(ipa));
            kokoroMissing.UnionWith(Kokoro.Missing(misaki));
            Assert.NotEmpty(ipa);
            Assert.NotEmpty(misaki);
            count++;
        }

        // Assert: the whole dictionary was rendered and nothing is outside the models' symbols
        Assert.True(count >= 130_000);
        Assert.Empty(piperMissing);
        Assert.Empty(kokoroMissing);
    }

    /// <summary>Proves every phone in every neighborhood of two phones (all 69 x 69 x 69 sequences) renders to symbols of the models, whatever the context rules do.</summary>
    [Fact]
    public void RenderingSubsystem_Coverage_EveryPhoneInEveryNeighborhood_UsesOnlySymbolsOfBothModels()
    {
        // Arrange
        var phones = Enumerable.Range(1, Phone.MaxCode).Select(code => Phone.FromCode((byte)code)).ToArray();
        var piperMissing = new HashSet<char>();
        var kokoroMissing = new HashSet<char>();

